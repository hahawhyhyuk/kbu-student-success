def guides_for_category(category: str) -> tuple[ServiceGuide, ...]:
    """선택한 사용자 흐름의 화면 설명을 메뉴 순서로 반환한다."""

    return tuple(guide for guide in SERVICE_GUIDES if guide.category == category)


def guides_for_role(role: str) -> tuple[ServiceGuide, ...]:
    """로그인 역할이 실제로 이용하는 화면 안내만 메뉴 순서로 반환한다.

    Parameters:
        role: ``student`` 또는 ``staff`` 역할 문자열.

    Returns:
        계정 진입점과 역할별 매뉴얼 자체를 제외한 업무 화면 안내.

    Assumptions:
        직접 URL 접근 범위는 ``src.access_control``의 allowlist를 단일 기준으로 쓴다.
    """

    from src.access_control import allowed_page_paths

    allowed_paths = set(allowed_page_paths(role)).difference(MANUAL_PAGE_PATHS)
    return tuple(guide for guide in SERVICE_GUIDES if guide.path in allowed_paths)


def guide_categories_for_role(role: str) -> tuple[str, ...]:
    """역할별 화면 안내에 실제로 존재하는 분류만 고정 순서로 반환한다."""

    available = {guide.category for guide in guides_for_role(role)}
    return tuple(category for category in GUIDE_CATEGORIES if category in available)


def documented_paths() -> set[str]:
    """사용설명서에 포함된 실제 화면 경로를 반환한다."""

    return {guide.path for guide in SERVICE_GUIDES} | set(MANUAL_PAGE_PATHS)
